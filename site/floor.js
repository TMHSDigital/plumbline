/*
 * The calibrated-model floor for ECE, reimplemented from plumbline's Python.
 *
 * This is a port of plumbline.metrics.calibration.synthetic_floor, and it is
 * meant to produce the same numbers, not numbers like them. It does that by
 * reproducing numpy's random stream draw for draw: the PCG64 bit generator,
 * numpy's ziggurat normal and exponential samplers, its Marsaglia-Tsang gamma,
 * and its beta. With the same seeds the Python uses (0 for the invented
 * probabilities, 1 for the bootstrap), every uniform, every Bernoulli outcome,
 * and every bin count is identical to what numpy draws. What remains is the
 * order floating point sums are taken in and last-bit differences between C's
 * and JavaScript's pow, log, and exp, which move the result around 1e-16.
 *
 * floor-golden.json holds values exported from the Python implementation, and
 * scripts/check_floor_parity.mjs fails CI when this file disagrees with them by
 * more than 1e-9. A single desynchronised draw shifts every draw after it and
 * moves the result by around 1e-3, so there is nothing in between: either the
 * streams agree and the numbers match to 1e-16, or they do not and the check
 * fails loudly.
 *
 * The ziggurat tables at the bottom are numpy's, copied from
 * numpy/random/src/distributions/ziggurat_constants.h at numpy v2.5.3.
 * numpy is BSD-3-Clause licensed, Copyright (c) 2005-2025 NumPy Developers.
 *
 * Loads as a plain script (browser, worker) or as a CommonJS module (Node).
 * No dependencies.
 */
