  /* ---------------------------------------------------------------- PCG64 */

  // numpy's PCG64: 128-bit LCG state, XSL-RR output, advanced before output.
  // 128-bit arithmetic is done in eight 16-bit limbs held in plain numbers so
  // that every partial product is exact in a double.

  // 2549297995355413924 * 2^64 + 4865540595714422341, low limb first.
  var MULT = limbs("2360ed051fc65da44385df649fccf645");

  function limbs(hex) {
    hex = hex.padStart(32, "0");
    var out = new Array(8);
    for (var k = 0; k < 8; k++) {
      out[k] = parseInt(hex.slice(32 - 4 * (k + 1), 32 - 4 * k), 16);
    }
    return out;
  }

  // The initial states numpy.random.default_rng(seed) arrives at, as
  // rng.bit_generator.state reports them. synthetic_floor only ever uses seeds
  // 0 and 1, so SeedSequence is not reimplemented; the parity check confirms
  // these against the Python on every run.
  var SEED_STATES = {
    0: {
      state: "35399562948360463058890781895381311971",
      inc: "87136372517582989555478159403783844777",
    },
    1: {
      state: "207833532711051698738587646355624148094",
      inc: "194290289479364712180083596243593368443",
    },
  };

  function decimalToHex(decimal) {
    // Decimal string to 32 hex digits, without BigInt, so it runs anywhere.
    var digits = decimal.split("").map(Number);
    var hex = "";
    while (digits.length && !(digits.length === 1 && digits[0] === 0)) {
      var remainder = 0;
      var next = [];
      for (var i = 0; i < digits.length; i++) {
        var value = remainder * 10 + digits[i];
        var q = Math.floor(value / 16);
        remainder = value - q * 16;
        if (next.length || q) next.push(q);
      }
      hex = remainder.toString(16) + hex;
      digits = next.length ? next : [0];
    }
    return hex || "0";
  }

  function Pcg64(stateDecimal, incDecimal) {
    this.s = limbs(decimalToHex(stateDecimal));
    this.inc = limbs(decimalToHex(incDecimal));
    this.hi = 0; // upper 32 bits of the last 64-bit output
    this.lo = 0; // lower 32 bits
  }

  Pcg64.prototype.next = function () {
    var s = this.s;
    var inc = this.inc;
    var s0 = s[0], s1 = s[1], s2 = s[2], s3 = s[3];
    var s4 = s[4], s5 = s[5], s6 = s[6], s7 = s[7];
    var m0 = MULT[0], m1 = MULT[1], m2 = MULT[2], m3 = MULT[3];
    var m4 = MULT[4], m5 = MULT[5], m6 = MULT[6], m7 = MULT[7];
    // state = state * MULT + inc, mod 2^128. Each column sums at most eight
    // products below 2^32, plus a carry, so it stays exact.
    var t, carry;
    t = s0 * m0 + inc[0];
    s[0] = t % 65536; carry = (t - s[0]) / 65536;
    t = s0 * m1 + s1 * m0 + inc[1] + carry;
    s[1] = t % 65536; carry = (t - s[1]) / 65536;
    t = s0 * m2 + s1 * m1 + s2 * m0 + inc[2] + carry;
    s[2] = t % 65536; carry = (t - s[2]) / 65536;
    t = s0 * m3 + s1 * m2 + s2 * m1 + s3 * m0 + inc[3] + carry;
    s[3] = t % 65536; carry = (t - s[3]) / 65536;
    t = s0 * m4 + s1 * m3 + s2 * m2 + s3 * m1 + s4 * m0 + inc[4] + carry;
    s[4] = t % 65536; carry = (t - s[4]) / 65536;
    t = s0 * m5 + s1 * m4 + s2 * m3 + s3 * m2 + s4 * m1 + s5 * m0 + inc[5] + carry;
    s[5] = t % 65536; carry = (t - s[5]) / 65536;
    t = s0 * m6 + s1 * m5 + s2 * m4 + s3 * m3 + s4 * m2 + s5 * m1 + s6 * m0 + inc[6] + carry;
    s[6] = t % 65536; carry = (t - s[6]) / 65536;
    t = s0 * m7 + s1 * m6 + s2 * m5 + s3 * m4 + s4 * m3 + s5 * m2 + s6 * m1 + s7 * m0 +
      inc[7] + carry;
    s[7] = t % 65536;

    // XSL-RR: rotate (high ^ low) right by the top six bits of the state.
    var xh = ((s[7] << 16) | s[6]) ^ ((s[3] << 16) | s[2]);
    var xl = ((s[5] << 16) | s[4]) ^ ((s[1] << 16) | s[0]);
    var rot = s[7] >>> 10;
    if (rot >= 32) {
      var swap = xh; xh = xl; xl = swap;
      rot -= 32;
    }
    if (rot === 0) {
      this.hi = xh >>> 0;
      this.lo = xl >>> 0;
    } else {
      this.hi = ((xh >>> rot) | (xl << (32 - rot))) >>> 0;
      this.lo = ((xl >>> rot) | (xh << (32 - rot))) >>> 0;
    }
  };

  // numpy's next_double: the top 53 bits of a 64-bit draw, times 2^-53.
  Pcg64.prototype.nextDouble = function () {
    this.next();
    return (this.hi * 2097152 + (this.lo >>> 11)) * 1.1102230246251565e-16;
  };

  function generator(seed) {
    var initial = SEED_STATES[seed];
    if (!initial || !initial.state) throw new Error("no recorded PCG64 state for seed " + seed);
    return new Pcg64(initial.state, initial.inc);
  }

  /* -------------------------------------------------------- distributions */

  // Line for line from numpy/random/src/distributions/distributions.c.

  function standardExponential(g) {
    for (;;) {
      g.next();
      var idx = (g.lo >>> 3) & 0xff;
      var ri = g.hi * 2097152 + (g.lo >>> 11); // the 64-bit draw >> 11
      var x = ri * WE[idx];
      if (ri < KE[idx]) return x;
      if (idx === 0) return EXP_R - Math.log1p(-g.nextDouble());
      if ((FE[idx - 1] - FE[idx]) * g.nextDouble() + FE[idx] < Math.exp(-x)) return x;
      // numpy recurses here; a loop draws the same sequence.
    }
  }

  function standardNormal(g) {
    for (;;) {
      g.next();
      var lo = g.lo;
      var idx = lo & 0xff;
      var sign = (lo >>> 8) & 1;
      // (draw >> 9) masked to 52 bits: bits 9..60 of the draw.
      var rabs = (g.hi & 0x1fffffff) * 8388608 + (lo >>> 9);
      var x = rabs * WI[idx];
      if (sign) x = -x;
      if (rabs < KI[idx]) return x;
      if (idx === 0) {
        for (;;) {
          var xx = -NOR_INV_R * Math.log1p(-g.nextDouble());
          var yy = -Math.log1p(-g.nextDouble());
          if (yy + yy > xx * xx) return (lo >>> 17) & 1 ? -(NOR_R + xx) : NOR_R + xx;
        }
      } else if ((FI[idx - 1] - FI[idx]) * g.nextDouble() + FI[idx] < Math.exp(-0.5 * x * x)) {
        return x;
      }
    }
  }

  function standardGamma(g, shape) {
    var U, V, X, Y;
    if (shape === 1.0) return standardExponential(g);
    if (shape === 0.0) return 0.0;
    if (shape < 1.0) {
      for (;;) {
        U = g.nextDouble();
        V = standardExponential(g);
        if (U <= 1.0 - shape) {
          X = Math.pow(U, 1.0 / shape);
          if (X <= V) return X;
        } else {
          Y = -Math.log((1 - U) / shape);
          X = Math.pow(1.0 - shape + shape * Y, 1.0 / shape);
          if (X <= V + Y) return X;
        }
      }
    }
    var b = shape - 1.0 / 3.0;
    var c = 1.0 / Math.sqrt(9 * b);
    for (;;) {
      do {
        X = standardNormal(g);
        V = 1.0 + c * X;
      } while (V <= 0.0);
      V = V * V * V;
      U = g.nextDouble();
      if (U < 1.0 - 0.0331 * (X * X) * (X * X)) return b * V;
      if (Math.log(U) < 0.5 * X * X + b * (1.0 - V + Math.log(V))) return b * V;
    }
  }

  function beta(g, a, b) {
    // numpy switches to Johnk's algorithm when both shapes are at most 1.
    // synthetic_floor's shapes always sum to its concentration of 6, so that
    // branch is unreachable here and is refused rather than ported untested.
    if (a <= 1.0 && b <= 1.0) throw new Error("beta shapes both <= 1 are not supported");
    var ga = standardGamma(g, a);
    var gb = standardGamma(g, b);
    return ga / (ga + gb);
  }

  /* ---------------------------------------------------------------- floor */

  var DEFAULT_N_BINS = 10;
  var DEFAULT_N_BOOT = 2000;
  var DEFAULT_CONCENTRATION = 6.0;

  // np.percentile(values, q) with the default linear method.
  function percentile(values, q) {
    var sorted = Float64Array.from(values).sort();
    var n = sorted.length;
    var quantile = q / 100;
    var virtual = n * quantile + (1 + quantile * (1 - 1 - 1)) - 1;
    var below = Math.floor(virtual);
    var gamma = virtual - below;
    if (below < 0) return sorted[0];
    if (below >= n - 1) return sorted[n - 1];
    var a = sorted[below];
    var b = sorted[below + 1];
    var diff = b - a;
    return gamma >= 0.5 ? b - diff * (1 - gamma) : a + diff * gamma;
  }

  function mean(values) {
    var total = 0;
    for (var i = 0; i < values.length; i++) total += values[i];
    return total / values.length;
  }

  /**
   * The ECE a perfectly calibrated model scores on n rows, from summary numbers.
   *
   * Mirrors synthetic_floor(n, n_bins, accuracy) with equal-width bins: invent n
   * predicted probabilities from Beta(accuracy * 6, (1 - accuracy) * 6), then
   * redraw every outcome from Bernoulli(p_i) n_boot times and read the ECE of
   * each resample. Returns { mean, p95, n, nBins, nBoot }.
   *
   * options.onProgress(fraction) is called during the bootstrap, for the page.
   */
  function syntheticFloor(n, nBins, accuracy, options) {
    options = options || {};
    var nBoot = options.nBoot || DEFAULT_N_BOOT;
    var concentration = options.concentration || DEFAULT_CONCENTRATION;
    var onProgress = options.onProgress;
    nBins = nBins || DEFAULT_N_BINS;

    if (!(Number.isInteger(n) && n >= 1)) throw new Error("n must be a whole number of rows, at least 1");
    if (!(Number.isInteger(nBins) && nBins >= 1)) throw new Error("the bin count must be a whole number, at least 1");
    if (!(accuracy > 0 && accuracy < 1)) throw new Error("accuracy must lie strictly inside (0, 1)");

    var seed = 0;
    var g = generator(seed);
    var a = accuracy * concentration;
    var b = (1.0 - accuracy) * concentration;
    var probabilities = new Float64Array(n);
    for (var i = 0; i < n; i++) probabilities[i] = beta(g, a, b);

    // _bootstrap_floor, equal-width binning.
    var index = new Int32Array(n);
    var counts = new Float64Array(nBins);
    var summed = new Float64Array(nBins);
    for (i = 0; i < n; i++) {
      var bin = Math.floor(probabilities[i] * nBins);
      if (bin < 0) bin = 0;
      if (bin > nBins - 1) bin = nBins - 1;
      index[i] = bin;
      counts[bin] += 1;
      summed[bin] += probabilities[i];
    }
    var meanProbability = new Float64Array(nBins);
    for (var k = 0; k < nBins; k++) {
      if (counts[k] > 0) meanProbability[k] = summed[k] / counts[k];
    }

    var boot = generator(seed + 1);
    var draws = new Float64Array(nBoot);
    var correct = new Float64Array(nBins);
    var every = Math.max(1, Math.floor(nBoot / 50));
    for (var r = 0; r < nBoot; r++) {
      correct.fill(0);
      for (i = 0; i < n; i++) {
        if (boot.nextDouble() < probabilities[i]) correct[index[i]] += 1;
      }
      var weighted = 0;
      for (k = 0; k < nBins; k++) {
        if (counts[k] > 0) {
          weighted += Math.abs(correct[k] / counts[k] - meanProbability[k]) * counts[k];
        }
      }
      draws[r] = weighted / n;
      if (onProgress && r % every === 0) onProgress(r / nBoot);
    }
    if (onProgress) onProgress(1);

    return { metric: "ece", mean: mean(draws), p95: percentile(draws, 95), n: n, nBins: nBins, nBoot: nBoot };
  }

  /* -------------------------------------------------------------- wording */

  // Python's "%.4f": round half to even on the exact binary value. toFixed
  // rounds exact ties up, which differs only when the value is a tie exactly.
  function fixed4(x) {
    var scaled = x * 10000;
    if (Math.abs(scaled) < 1e15 && scaled - Math.floor(scaled) === 0.5 && x * 10000 === scaled) {
      var down = Math.floor(scaled);
      var even = down % 2 === 0 ? down : down + 1;
      return (even / 10000).toFixed(4);
    }
    return x.toFixed(4);
  }

  function isDistinguishable(measured, floor) {
    return measured > floor.p95;
  }

  // plumbline.metrics.calibration._judgment, word for word.
  function judgment(measured, floor) {
    if (isDistinguishable(measured, floor)) {
      return "miscalibration is distinguishable from sampling noise.";
    }
    return (
      "INCONCLUSIVE at this sample size. A perfectly calibrated model would " +
      "often score this badly on this many rows, so this dataset cannot tell " +
      "the two apart. This is not a clean bill of health: nothing was " +
      "established either way. Collect more rows to make the question " +
      "answerable."
    );
  }

  // CalibrationFigure.statement() for an ECE figure with equal-width bins.
  function statement(measured, floor) {
    return (
      "ECE " + fixed4(measured) + " over " + floor.n + " rows (" + floor.nBins +
      " equal width bins), against a calibrated-model floor of " + fixed4(floor.mean) +
      " (95th percentile " + fixed4(floor.p95) + "): " + judgment(measured, floor)
    );
  }

